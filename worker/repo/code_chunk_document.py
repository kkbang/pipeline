def build_code_chunk_id(
    *,
    repo_id: str,
    file_path: str,
    chunk_type: str,
    start_line: int,
    end_line: int,
    symbol_name: str,
    chunker_version: str,
) -> str:
    digest_input = "|".join(
        [
            repo_id,
            file_path,
            chunk_type,
            str(start_line),
            str(end_line),
            symbol_name,
            chunker_version,
        ]
    )
    return hashlib.sha1(digest_input.encode("utf-8")).hexdigest()


def _ordered_unique(values: list[str], *, cap: int) -> list[str]:
    normalized_cap = max(0, cap)
    ordered: list[str] = []
    seen: set[str] = set()
    for value in values:
        normalized = str(value or "").strip()
        if not normalized or normalized in seen:
            continue
        seen.add(normalized)
        ordered.append(normalized)
        if normalized_cap and len(ordered) >= normalized_cap:
            break
    return ordered


def _decode_node_text(content_bytes: bytes, node: Node) -> str:
    try:
        return content_bytes[node.start_byte : node.end_byte].decode("utf-8", errors="ignore")
    except Exception:  # noqa: BLE001 - best effort decode only
        return ""


def _contains_generated_marker(raw_code: str) -> bool:
    header = "\n".join(raw_code.splitlines()[:5]).lower()
    return any(marker in header for marker in COMMENT_MARKERS)


def _should_skip_decorated_python_node(language: str, node: Node) -> bool:
    parent = getattr(node, "parent", None)
    if language != "python" or parent is None:
        return False
    node_type = str(node.type or "")
    parent_type = str(parent.type or "")
    if node_type in {"function_definition", "class_definition"} and parent_type == "decorated_definition":
        return True
    return False


def _get_decorated_python_target(node: Node) -> Node | None:
    for child in node.children:
        if not child.is_named:
            continue
        child_type = str(child.type or "")
        if child_type in {"class_definition", "function_definition"}:
            return child
    return None


def _node_type_tokens(node_type: str) -> set[str]:
    return {token for token in re.split(r"[^a-z0-9]+|_", node_type.lower()) if token}


def _node_matches_chunk_type(language: str, node: Node) -> str | None:
    node_type = str(node.type or "")
    if not node_type or not node.is_named:
        return None

    if language == "python" and node_type == "decorated_definition":
        decorated_target = _get_decorated_python_target(node)
        if decorated_target is not None:
            return _node_matches_chunk_type(language, decorated_target)

    function_node_types = FUNCTION_NODE_TYPES_BY_LANGUAGE.get(language, set())
    class_node_types = CLASS_NODE_TYPES_BY_LANGUAGE.get(language, set())

    if node_type in function_node_types:
        return "function"
    if node_type in class_node_types:
        return "class"

    tokens = _node_type_tokens(node_type)
    if any(group.issubset(tokens) for group in FUNCTION_INFERENCE_TOKEN_GROUPS):
        return "function"
    if any(group.issubset(tokens) for group in CLASS_INFERENCE_TOKEN_GROUPS):
        return "class"
    return None


def _extract_symbol_name(content_bytes: bytes, node: Node) -> str:
    if str(node.type or "") == "decorated_definition":
        decorated_target = _get_decorated_python_target(node)
        if decorated_target is not None:
            return _extract_symbol_name(content_bytes, decorated_target)

    declarator_child = _find_child_by_field_names(node, ("declarator",))
    if declarator_child is not None:
        declarator_name = _extract_symbol_name(content_bytes, declarator_child)
        if declarator_name:
            return declarator_name

    direct_name_child = _find_child_by_field_names(node, ("name",))
    if direct_name_child is not None:
        direct_name = _decode_node_text(content_bytes, direct_name_child).strip()
        if direct_name:
            return direct_name

    for child in node.children:
        if not child.is_named:
            continue
        child_type = str(child.type or "")
        lowered_child_type = child_type.lower()
        if (
            child_type in PARAMETER_CONTAINER_TYPES
            or "body" in child_type
            or "block" in child_type
            or "type" in lowered_child_type
            or child_type in {"storage_class_specifier", "visibility_modifier", "modifiers"}
        ):
            continue
        if child_type in SYMBOL_NAME_NODE_TYPES:
            value = _decode_node_text(content_bytes, child).strip()
            if value:
                return value

    current = node
    for _ in range(4):
        parent = getattr(current, "parent", None)
        if parent is None:
            break
        for field_names in PARENT_SYMBOL_FIELD_NAME_GROUPS:
            candidate = _find_child_by_field_names(parent, field_names)
            if candidate is None:
                continue
            if (
                int(candidate.start_byte) == int(current.start_byte)
                and int(candidate.end_byte) == int(current.end_byte)
            ):
                continue
            identifiers = _collect_identifier_texts(content_bytes, candidate)
            if identifiers:
                return identifiers[-1]
            candidate_text = _decode_node_text(content_bytes, candidate).strip()
            if candidate_text:
                identifier_matches = IDENTIFIER_TEXT_RE.findall(candidate_text)
                if identifier_matches:
                    return identifier_matches[-1]
        current = parent

    return ""


def _estimate_param_count(raw_code: str) -> int:
    header_lines = raw_code.splitlines()[:3]
    header = " ".join(line.strip() for line in header_lines)
    match = re.search(r"\((.*?)\)", header)
    if not match:
        return 0
    inside = match.group(1).strip()
    if not inside:
        return 0
    parts = [chunk.strip() for chunk in inside.split(",")]
    return len([part for part in parts if part])


def _collect_identifier_texts(content_bytes: bytes, node: Node) -> list[str]:
    tokens: list[str] = []
    stack = [node]
    while stack:
        current = stack.pop()
        if not current.is_named:
            continue
        current_type = str(current.type or "")
        if current_type in IDENTIFIER_NODE_TYPES:
            token = _decode_node_text(content_bytes, current).strip()
            if token:
                tokens.append(token)
        stack.extend(reversed(list(current.children)))
    return tokens


def _ordered_unique_set(values: list[str]) -> set[str]:
    return {value for value in _ordered_unique(values, cap=0) if value}


def _find_child_by_field_names(node: Node, field_names: tuple[str, ...]) -> Node | None:
    child_by_field_name = getattr(node, "child_by_field_name", None)
    if not callable(child_by_field_name):
        return None
    for field_name in field_names:
        child = child_by_field_name(field_name)
        if child is not None:
            return child
    return None


def _find_parameter_container(node: Node) -> Node | None:
    for child in node.children:
        if not child.is_named:
            continue
        child_type = str(child.type or "")
        if child_type in PARAMETER_BINDING_CONTAINER_TYPES:
            return child
    return None


def _is_import_like_node(node_type: str) -> bool:
    lowered = node_type.lower()
    return any(marker in lowered for marker in IMPORT_NODE_TYPE_MARKERS)


def _is_local_variable_like_node(node_type: str) -> bool:
    lowered = node_type.lower()
    return any(marker in lowered for marker in LOCAL_VARIABLE_NODE_TYPE_MARKERS)


def _collect_imported_symbols(content_bytes: bytes, node: Node) -> set[str]:
    imported_symbols: set[str] = set()
    stack = [node]
    while stack:
        current = stack.pop()
        if not current.is_named:
            continue
        current_type = str(current.type or "")
        if _is_import_like_node(current_type):
            alias_child = _find_child_by_field_names(current, ("alias", "name"))
            if alias_child is not None:
                imported_symbols.update(_ordered_unique_set(_collect_identifier_texts(content_bytes, alias_child)))
            else:
                imported_symbols.update(_ordered_unique_set(_collect_identifier_texts(content_bytes, current)))
        stack.extend(reversed(list(current.children)))
    return imported_symbols


def _collect_binding_identifier_texts(content_bytes: bytes, node: Node) -> list[str]:
    tokens: list[str] = []
    stack = [node]
    while stack:
        current = stack.pop()
        if not current.is_named:
            continue
        current_type = str(current.type or "")
        lowered_type = current_type.lower()
        if "type" in lowered_type:
            continue
        if current_type in IDENTIFIER_NODE_TYPES:
            token = _decode_node_text(content_bytes, current).strip()
            if token:
                tokens.append(token)
            continue
        stack.extend(reversed(list(current.children)))
    return tokens


def _allows_assignment_bindings(language: str) -> bool:
    return language in {"php", "python", "ruby", "shell"}


def _is_assignment_expression_like(node_type: str) -> bool:
    lowered = node_type.lower()
    return "assignment" in lowered and "declaration" not in lowered and "declarator" not in lowered


def _is_plain_binding_target(node: Node) -> bool:
    node_type = str(node.type or "").lower()
    if any(marker in node_type for marker in NON_BINDING_TARGET_NODE_MARKERS):
        return False
    return True


def _collect_local_binding_symbols(content_bytes: bytes, node: Node, language: str) -> set[str]:
    local_symbols: set[str] = set()
    allow_assignment_bindings = _allows_assignment_bindings(language)
    stack = [node]
    while stack:
        current = stack.pop()
        if not current.is_named:
            continue
        current_type = str(current.type or "")
        if _is_import_like_node(current_type):
            stack.extend(reversed(list(current.children)))
            continue

        binding_child = _find_child_by_field_names(current, LOCAL_BINDING_FIELD_NAMES)
        lowered_type = current_type.lower()
        if binding_child is not None and (
            _is_local_variable_like_node(current_type) or "parameter" in lowered_type
        ):
            if _is_assignment_expression_like(current_type):
                if not allow_assignment_bindings or not _is_plain_binding_target(binding_child):
                    stack.extend(reversed(list(current.children)))
                    continue
            local_symbols.update(_ordered_unique_set(_collect_binding_identifier_texts(content_bytes, binding_child)))
        elif binding_child is None and ("spec" in lowered_type or current_type in {"with_item"}):
            local_symbols.update(_ordered_unique_set(_collect_binding_identifier_texts(content_bytes, current)))

        parameter_child = _find_parameter_container(current)
        if parameter_child is not None:
            local_symbols.update(
                _ordered_unique_set(_collect_binding_identifier_texts(content_bytes, parameter_child))
            )

        stack.extend(reversed(list(current.children)))
    return local_symbols


def _collect_nested_symbol_names(content_bytes: bytes, node: Node, language: str) -> tuple[set[str], set[str]]:
    function_symbols: set[str] = set()
    class_symbols: set[str] = set()
    stack = list(reversed(list(node.children)))
    while stack:
        current = stack.pop()
        if not current.is_named:
            continue
        chunk_type = _node_matches_chunk_type(language, current)
        if chunk_type is not None and not _should_skip_decorated_python_node(language, current):
            if (
                language in {"javascript", "typescript"}
                and chunk_type == "function"
                and str(current.type or "") == "arrow_function"
                and _is_inline_callback_arrow_function(current)
            ):
                stack.extend(reversed(list(current.children)))
                continue
            symbol_name = _extract_symbol_name(content_bytes, current).strip()
            if symbol_name:
                if chunk_type == "function":
                    function_symbols.add(symbol_name)
                elif chunk_type == "class":
                    class_symbols.add(symbol_name)
        stack.extend(reversed(list(current.children)))
    return function_symbols, class_symbols


def _build_anonymization_context(content_bytes: bytes, node: Node, language: str) -> AnonymizationContext:
    imported_symbols = _collect_imported_symbols(content_bytes, node)
    local_variable_symbols = _collect_local_binding_symbols(content_bytes, node, language)
    local_function_symbols, local_class_symbols = _collect_nested_symbol_names(content_bytes, node, language)
    local_variable_symbols -= imported_symbols
    local_function_symbols -= imported_symbols
    local_class_symbols -= imported_symbols
    return AnonymizationContext(
        imported_symbols=imported_symbols,
        local_variable_symbols=local_variable_symbols,
        local_function_symbols=local_function_symbols,
        local_class_symbols=local_class_symbols,
    )


def _collect_comment_ranges(node: Node) -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    stack = [node]
    while stack:
        current = stack.pop()
        node_type = str(current.type or "")
        if "comment" in node_type:
            ranges.append((current.start_byte, current.end_byte))
        stack.extend(reversed(list(current.children)))
    ranges.sort()
    return ranges


def _remove_comment_ranges(raw_bytes: bytes, comment_ranges: list[tuple[int, int]], start_byte: int) -> bytes:
    if not comment_ranges:
        return raw_bytes

    pieces: list[bytes] = []
    cursor = start_byte
    end_byte = start_byte + len(raw_bytes)
    for comment_start, comment_end in comment_ranges:
        bounded_start = max(start_byte, min(comment_start, end_byte))
        bounded_end = max(start_byte, min(comment_end, end_byte))
        if bounded_start > cursor:
            pieces.append(raw_bytes[cursor - start_byte : bounded_start - start_byte])
        cursor = max(cursor, bounded_end)
    if cursor < end_byte:
        pieces.append(raw_bytes[cursor - start_byte : end_byte - start_byte])
    return b"".join(pieces)


def _normalize_code(raw_code: str, raw_bytes: bytes, node: Node) -> str:
    comment_ranges = _collect_comment_ranges(node)
    normalized_bytes = _remove_comment_ranges(raw_bytes, comment_ranges, node.start_byte)
    normalized_text = normalized_bytes.decode("utf-8", errors="ignore")

    collapsed_lines: list[str] = []
    previous_blank = False
    for line in normalized_text.splitlines():
        compact_line = re.sub(r"[ \t]+", " ", line.rstrip())
        if not compact_line.strip():
            if previous_blank:
                continue
            collapsed_lines.append("")
            previous_blank = True
            continue
        collapsed_lines.append(compact_line)
        previous_blank = False

    return "\n".join(collapsed_lines).strip()


